# Operators in Python


# 1. Arithmetic Operators
# +  Addition
# -  Subtraction
# *  Multiplication
# /  Division
# %  Modulus
# ** Exponentiation
# // Floor Division

# 2. Assignment Operators
# =   Assign
# +=  Add and assign
# -=  Subtract and assign
# *=  Multiply and assign
# /=  Divide and assign
# %=  Modulus and assign
# //= Floor divide and assign
# **= Exponentiate and assign

# 3. Comparison Operators
# ==  Equal to
# !=  Not equal to
# >   Greater than
# <   Less than
# >=  Greater than or equal to
# <=  Less than or equal to

# 4. Logical Operators
# and  Logical AND
# or   Logical OR
# not  Logical NOT

# 5. Bitwise Operators
# &   Bitwise AND
# |   Bitwise OR
# ^   Bitwise XOR
# ~   Bitwise NOT
# <<  Bitwise left shift
# >>  Bitwise right shift

# 6. Membership Operators
# in     Value found in sequence
# not in Value not found in sequence

# 7. Identity Operators
# is     Same object
# is not Not same object