# Data Types

a = 10 # a is an integer

b  = 2.22 # b is a floating point number

c  = True # c is a boolean data type

d = "Abdul Basit" # d is a String

e = None # e is a none 

# Common data types in Python:
# int        - Integer numbers (e.g., 1, -5, 100)
# float      - Floating point numbers (e.g., 2.5, -0.1)
# bool       - Boolean values (True, False)
# str        - String (e.g., "hello")
# NoneType   - Represents the absence of a value (None)
# list       - Ordered, mutable collection (e.g., [1, 2, 3])
# tuple      - Ordered, immutable collection (e.g., (1, 2, 3))
# set        - Unordered collection of unique elements (e.g., {1, 2, 3})
# dict       - Key-value pairs (e.g., {"a": 1, "b": 2})
# bytes      - Immutable sequence of bytes (e.g., b'abc')
# bytearray  - Mutable sequence of bytes
# complex    - Complex numbers (e.g., 1+2j)